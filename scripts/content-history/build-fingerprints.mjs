// Builds src/data/contentHistoryFingerprints.json: fingerprints of every past
// built-in version of the study sheets, clinic guide templates, articles, and
// weekly curriculum, read straight from git history.
//
// Why: rotations created before contentCustomizations existed store a full
// copy of that content. The app treats a stored item as "not customized" (and
// shows the current built-in version instead) when its fingerprint matches any
// built-in version it could have been copied from. Rotations published after
// this change record their customizations explicitly, so this only needs to
// cover history up to that change — rerunning it later is harmless.
//
// Usage: npm run content:fingerprints   (needs full git history, not a shallow clone)
import { execFileSync } from "node:child_process";
import { mkdirSync, rmSync, existsSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { pathToFileURL } from "node:url";
import { build } from "esbuild";

const ROOT = resolve(import.meta.dirname, "../..");
const TMP = join(ROOT, ".content-history-tmp");
const OUT = join(ROOT, "src/data/contentHistoryFingerprints.json");
const git = (...args) => execFileSync("git", args, { cwd: ROOT, encoding: "utf8", maxBuffer: 64 * 1024 * 1024 });

if (git("rev-parse", "--is-shallow-repository").trim() === "true") {
  console.error("Shallow clone — run `git fetch --unshallow` first so every past version is included.");
  process.exit(1);
}

rmSync(TMP, { recursive: true, force: true });
mkdirSync(TMP, { recursive: true });

await build({
  entryPoints: [join(ROOT, "src/utils/contentFingerprint.ts")],
  bundle: true, format: "esm", platform: "node", outfile: join(TMP, "fingerprint.mjs"), logLevel: "silent",
});
const { contentFingerprint } = await import(pathToFileURL(join(TMP, "fingerprint.mjs")).href);

const commits = [...new Set(git("rev-list", "HEAD", "--", "src/data").trim().split("\n").filter(Boolean))];
const found = { studySheets: new Set(), clinicGuideTemplates: new Set(), articles: new Set(), curriculum: new Set() };
let used = 0;

for (const sha of commits) {
  const dir = join(TMP, sha);
  mkdirSync(dir, { recursive: true });
  execFileSync("sh", ["-c", `git archive ${sha} src | tar -x -C "${dir}"`], { cwd: ROOT });
  const has = (base) => [".ts", ".js", ".tsx", ".jsx"].some((ext) => existsSync(join(dir, base + ext)));
  if (!has("src/data/constants")) continue;
  const lines = [
    `export * as constants from "./src/data/constants";`,
    has("src/data/clinicGuides") ? `export * as clinic from "./src/data/clinicGuides";` : `export const clinic = {};`,
  ];
  writeFileSync(join(dir, "entry.js"), lines.join("\n"));
  try {
    await build({
      entryPoints: [join(dir, "entry.js")],
      bundle: true, format: "esm", platform: "node", packages: "external", logLevel: "silent",
      outfile: join(dir, "bundle.mjs"),
      loader: { ".js": "jsx", ".png": "empty", ".jpg": "empty", ".svg": "empty", ".css": "empty" },
      jsx: "automatic",
    });
    const mod = await import(pathToFileURL(join(dir, "bundle.mjs")).href);
    const { STUDY_SHEETS = {}, ARTICLES = {}, WEEKLY = {} } = mod.constants;
    const CLINIC_GUIDES = mod.clinic.CLINIC_GUIDES || {};
    for (const [, sheets] of Object.entries(STUDY_SHEETS)) {
      for (const sheet of Array.isArray(sheets) ? sheets : []) {
        if (sheet?.id) found.studySheets.add(contentFingerprint("studySheets", sheet.id, sheet));
      }
    }
    for (const [topic, template] of Object.entries(CLINIC_GUIDES)) {
      found.clinicGuideTemplates.add(contentFingerprint("clinicGuideTemplates", topic, template));
    }
    for (const [week, list] of Object.entries(ARTICLES)) found.articles.add(contentFingerprint("articles", week, list));
    for (const [week, module] of Object.entries(WEEKLY)) found.curriculum.add(contentFingerprint("curriculum", week, module));
    used += 1;
  } catch (error) {
    console.warn(`skipped ${sha.slice(0, 7)}: ${String(error?.message || error).split("\n")[0]}`);
  }
}

rmSync(TMP, { recursive: true, force: true });
const output = {
  note: "Generated by scripts/content-history/build-fingerprints.mjs — fingerprints of past built-in content versions.",
  commitsRead: used,
  studySheets: [...found.studySheets].sort(),
  clinicGuideTemplates: [...found.clinicGuideTemplates].sort(),
  articles: [...found.articles].sort(),
  curriculum: [...found.curriculum].sort(),
};
writeFileSync(OUT, JSON.stringify(output, null, 2) + "\n");
console.log(`Read ${used}/${commits.length} commits → ${output.studySheets.length} study sheet, ${output.clinicGuideTemplates.length} clinic template, ${output.articles.length} article-week, ${output.curriculum.length} curriculum-week versions.`);
